-- WallpaperHub roadmap content schema.
-- Admin CRUD is handled by the server using its private Supabase service key.
-- Public and authenticated browser roles intentionally have no direct table access.
CREATE TABLE IF NOT EXISTS public.roadmap_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category text NOT NULL DEFAULT 'general'
    CHECK (category IN ('wallpapers','rewards','studio','community','identity','ai','performance','general')),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 180),
  summary text NOT NULL DEFAULT '' CHECK (char_length(summary) <= 500),
  content text NOT NULL DEFAULT '' CHECK (char_length(content) <= 6000),
  bullets jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(bullets) = 'array'),
  image_url text,
  image_key text,
  status text NOT NULL DEFAULT 'planned'
    CHECK (status IN ('planned','in_progress','released')),
  sort_order integer NOT NULL DEFAULT 100 CHECK (sort_order BETWEEN 0 AND 10000),
  is_published boolean NOT NULL DEFAULT false,
  created_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS roadmap_items_public_order_idx
  ON public.roadmap_items (is_published, sort_order, created_at);
CREATE INDEX IF NOT EXISTS roadmap_items_category_idx
  ON public.roadmap_items (category, sort_order);

ALTER TABLE public.roadmap_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.roadmap_items FROM anon, authenticated;
GRANT ALL ON TABLE public.roadmap_items TO service_role;
REVOKE ALL ON SEQUENCE public.roadmap_items_id_seq FROM anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.roadmap_items_id_seq TO service_role;
