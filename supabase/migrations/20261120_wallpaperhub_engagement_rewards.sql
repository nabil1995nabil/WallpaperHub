-- WallpaperHub engagement and active-time rewards
-- Run this file once in Supabase SQL Editor before relying on the new reward endpoints.
-- Rewards are server-side, user-scoped, and idempotent.

begin;

create table if not exists public.user_points_reward_events (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    event_key text not null,
    reward_type text not null check (reward_type in ('like', 'comment', 'active_time')),
    points numeric(12,2) not null check (points > 0),
    reason text not null,
    reference_id text,
    created_at timestamptz not null default now(),
    constraint user_points_reward_events_user_event_unique unique (user_id, event_key)
);

create index if not exists user_points_reward_events_user_created_idx
    on public.user_points_reward_events (user_id, created_at desc);

create table if not exists public.user_active_reward_state (
    user_id uuid primary key references auth.users(id) on delete cascade,
    last_heartbeat_at timestamptz not null default now(),
    active_seconds bigint not null default 0 check (active_seconds >= 0),
    awarded_cycles bigint not null default 0 check (awarded_cycles >= 0),
    updated_at timestamptz not null default now()
);

alter table public.user_points_reward_events enable row level security;
alter table public.user_active_reward_state enable row level security;

revoke all on public.user_points_reward_events from anon, authenticated;
revoke all on public.user_active_reward_state from anon, authenticated;

create or replace function public.award_wallpaperhub_engagement_reward(
    p_user_id uuid,
    p_reward_type text,
    p_reference_id text
)
returns table(success boolean, awarded boolean, points numeric, daily_limit boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_points numeric(12,2);
    v_event_key text;
    v_comment_count integer;
    v_wallpaper_owner text;
begin
    if p_user_id is null or nullif(trim(p_reference_id), '') is null then
        raise exception 'Invalid reward reference';
    end if;

    perform pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));

    if p_reward_type = 'like' then
        if not exists (
            select 1 from public.likes l
            where l.user_id::text = p_user_id::text
              and l.wallpaper_id::text = p_reference_id
        ) then
            raise exception 'Like action is not present';
        end if;

        select w.user_id::text into v_wallpaper_owner
        from public.wallpapers w
        where w.id::text = p_reference_id
        limit 1;

        if v_wallpaper_owner is not null and v_wallpaper_owner = p_user_id::text then
            return query select true, false, 0::numeric, false;
            return;
        end if;

        -- Avoid rewarding an account again for likes already paid by the legacy points ledger.
        if exists (
            select 1 from public.wallpaper_points_ledger old_entry
            where old_entry.user_id::text = p_user_id::text
              and old_entry.wallpaper_id::text = p_reference_id
              and lower(coalesce(old_entry.reason, '')) like '%like%'
        ) then
            return query select true, false, 0::numeric, false;
            return;
        end if;

        v_points := 0.90;
        v_event_key := 'wallpaper_like:' || p_reference_id;

    elsif p_reward_type = 'comment' then
        if not exists (
            select 1 from public.comments c
            where c.id::text = p_reference_id
              and c."userId"::text = p_user_id::text
        ) then
            raise exception 'Comment action is not present';
        end if;

        select count(*)::integer into v_comment_count
        from public.user_points_reward_events e
        where e.user_id = p_user_id
          and e.reward_type = 'comment'
          and e.created_at >= date_trunc('day', now());

        -- Limit rewarded comments to 10 per UTC day to discourage comment spam.
        if v_comment_count >= 10 then
            return query select true, false, 0::numeric, true;
            return;
        end if;

        v_points := 0.10;
        v_event_key := 'wallpaper_comment:' || p_reference_id;

    else
        raise exception 'Unsupported engagement reward type';
    end if;

    insert into public.user_points_reward_events
        (user_id, event_key, reward_type, points, reason, reference_id)
    values
        (p_user_id, v_event_key, p_reward_type, v_points,
         case when p_reward_type = 'like' then 'wallpaper_like' else 'wallpaper_comment' end,
         p_reference_id)
    on conflict (user_id, event_key) do nothing;

    if not found then
        return query select true, false, 0::numeric, false;
        return;
    end if;

    return query select true, true, v_points, false;
end;
$$;

create or replace function public.record_wallpaperhub_active_time_reward(p_user_id uuid)
returns table(
    success boolean,
    awarded integer,
    points numeric,
    active_seconds bigint,
    seconds_to_next_reward integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
    v_now timestamptz := clock_timestamp();
    v_state public.user_active_reward_state%rowtype;
    v_delta numeric;
    v_added integer := 0;
    v_old_cycles bigint;
    v_new_seconds bigint;
    v_new_cycles bigint;
    v_due integer := 0;
    v_cycle bigint;
begin
    if p_user_id is null then
        raise exception 'User is required';
    end if;

    insert into public.user_active_reward_state (user_id, last_heartbeat_at)
    values (p_user_id, v_now)
    on conflict (user_id) do nothing;

    select * into v_state
    from public.user_active_reward_state
    where user_id = p_user_id
    for update;

    v_delta := extract(epoch from (v_now - v_state.last_heartbeat_at));

    -- Heartbeats arrive about once per minute. Count only plausible intervals.
    -- Very short duplicate pings do not reset the baseline; long gaps do not earn time.
    if v_delta >= 35 and v_delta <= 125 then
        v_added := least(90, floor(v_delta)::integer);
        update public.user_active_reward_state
        set last_heartbeat_at = v_now,
            active_seconds = active_seconds + v_added,
            updated_at = v_now
        where user_id = p_user_id;
    elsif v_delta > 125 then
        update public.user_active_reward_state
        set last_heartbeat_at = v_now,
            updated_at = v_now
        where user_id = p_user_id;
    end if;

    select * into v_state
    from public.user_active_reward_state
    where user_id = p_user_id;

    v_new_seconds := v_state.active_seconds;
    v_old_cycles := v_state.awarded_cycles;
    v_new_cycles := floor(v_new_seconds / 600.0)::bigint;
    v_due := greatest(0, (v_new_cycles - v_old_cycles)::integer);

    if v_due > 0 then
        for v_cycle in (v_old_cycles + 1)..v_new_cycles loop
            insert into public.user_points_reward_events
                (user_id, event_key, reward_type, points, reason, reference_id)
            values
                (p_user_id, 'active_time:' || v_cycle::text, 'active_time',
                 0.25, 'active_time_10_minutes', v_cycle::text)
            on conflict (user_id, event_key) do nothing;
        end loop;

        update public.user_active_reward_state
        set awarded_cycles = v_new_cycles,
            updated_at = v_now
        where user_id = p_user_id;
    end if;

    return query
    select true,
           v_due,
           (v_due::numeric * 0.25)::numeric,
           v_new_seconds,
           (600 - (v_new_seconds % 600))::integer;
end;
$$;

create or replace function public.get_wallpaperhub_reward_points_total(p_user_id uuid)
returns numeric
language sql
stable
security definer
set search_path = public
as $$
    select coalesce(sum(e.points), 0)::numeric
    from public.user_points_reward_events e
    where e.user_id = p_user_id;
$$;

revoke all on function public.award_wallpaperhub_engagement_reward(uuid, text, text) from public, anon, authenticated;
revoke all on function public.record_wallpaperhub_active_time_reward(uuid) from public, anon, authenticated;
revoke all on function public.get_wallpaperhub_reward_points_total(uuid) from public, anon, authenticated;

grant execute on function public.award_wallpaperhub_engagement_reward(uuid, text, text) to service_role;
grant execute on function public.record_wallpaperhub_active_time_reward(uuid) to service_role;
grant execute on function public.get_wallpaperhub_reward_points_total(uuid) to service_role;

commit;
